private void configurarCalendarios() {

    jDateChooser2.setDateFormatString("dd/MM/yyyy");
    jDateChooser1.setDateFormatString("dd/MM/yyyy");

    jDateChooser2.setLocale(Locale.forLanguageTag("es-MX"));
    jDateChooser1.setLocale(Locale.forLanguageTag("es-MX"));

    LocalDate hoy = LocalDate.now();
    LocalDate inicio = hoy.minusDays(6);

    Date fechaDesde = Date.from(
            inicio.atStartOfDay(ZoneId.systemDefault())
                    .toInstant()
    );

    Date fechaHasta = Date.from(
            hoy.atStartOfDay(ZoneId.systemDefault())
                    .toInstant()
    );

    jDateChooser2.setDate(fechaDesde);
    jDateChooser1.setDate(fechaHasta);
}

private LocalDate convertirFecha(Date fecha) {

    return fecha.toInstant() .atZone(ZoneId.systemDefault()) .toLocalDate();
}
  
