private void consultar() {

    if (!btnConsultar.isEnabled()) {
        return;
    }

    if (jDateChooser2.getDate() == null ||
            jDateChooser1.getDate() == null) {

        JOptionPane.showMessageDialog(
                this,
                "Selecciona ambas fechas.",
                "Fechas requeridas",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    final LocalDate desde =
            convertirFecha(jDateChooser2.getDate());

    final LocalDate hasta =
            convertirFecha(jDateChooser1.getDate());

    if (desde.isAfter(hasta)) {

        JOptionPane.showMessageDialog(
                this,
                "La fecha \"Desde\" no puede ser posterior a la fecha \"Hasta\".",
                "Rango no válido",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    final String categoria =
            (String) cmbCategoria.getSelectedItem();

    btnConsultar.setEnabled(false);
    cmbCategoria.setEnabled(false);
    jDateChooser1.setEnabled(false);
    jDateChooser2.setEnabled(false);

    new SwingWorker<DelegateReporte.Resumen, Void>() {

        @Override
        protected DelegateReporte.Resumen doInBackground() {

            return facade.consultar(
                    usuarioActual,
                    desde,
                    hasta,
                    categoria
            );
        }

        @Override
        protected void done() {

            try {

                mostrarResultado(get(), desde, hasta);

            } catch (InterruptedException ex) {

                Thread.currentThread().interrupt();

            } catch (ExecutionException ex) {

                limpiarResultados();

                Throwable causa = ex.getCause();

                String mensaje;

                if (causa instanceof SecurityException ||
                        causa instanceof IllegalArgumentException) {

                    mensaje = causa.getMessage();

                } else {

                    causa.printStackTrace();

                    mensaje =  "No se pudo consultar el reporte. Intenta de nuevo.";
                }

                JOptionPane.showMessageDialog( ReportesPanel.this, mensaje, "Reportes", JOptionPane.WARNING_MESSAGE  );

            } finally {

                btnConsultar.setEnabled(true);
                cmbCategoria.setEnabled(true);
                jDateChooser1.setEnabled(true);
                jDateChooser2.setEnabled(true);
            }
        }

    }.execute();
}

private void mostrarResultado(DelegateReporte.Resumen r, LocalDate desde, LocalDate hasta) {
    lblVentasTotales.setText(MONEDA.format(r.total()));
    lblNumVentas.setText(String.valueOf(r.ventas()));
    lblTicketPromedio.setText(MONEDA.format(r.promedio()));
    lblProductosVendidos.setText(String.valueOf(r.productos()));

    ((GraficaBarras) graficaDias).setDatos(completarDias(r.porDia(), desde, hasta));
    ((GraficaDona) graficaCategorias).setDatos(r.porCategoria());
}

    private Map<LocalDate, BigDecimal> completarDias(Map<LocalDate, BigDecimal> porDia, LocalDate desde, LocalDate hasta) {
        Map<LocalDate, BigDecimal> completo = new TreeMap<>();
        if (desde.plusDays(31).isBefore(hasta)) { // periodos muy largos, solo los dias con ventas
            completo.putAll(porDia);
            return completo;
        }
        for (LocalDate d = desde; !d.isAfter(hasta); d = d.plusDays(1)) {
            completo.put(d, porDia.getOrDefault(d, BigDecimal.ZERO));
        }
        return completo;
    }

    private void limpiarResultados() {
        lblVentasTotales.setText(MONEDA.format(BigDecimal.ZERO));
        lblNumVentas.setText("0");
        lblTicketPromedio.setText(MONEDA.format(BigDecimal.ZERO));
        lblProductosVendidos.setText("0");
       ((GraficaBarras) graficaDias).setDatos(new TreeMap<>());
        ((GraficaDona) graficaCategorias).setDatos(new LinkedHashMap<>());;
    }
    
    
    private static class GraficaBarras extends JPanel {
        private Map<LocalDate, BigDecimal> datos = new TreeMap<>();

        GraficaBarras() {
            setOpaque(false);
        }

        void setDatos(Map<LocalDate, BigDecimal> datos) {
            this.datos = datos;
            repaint();
        }

        @Override
        protected void paintComponent(Graphics g) {
            super.paintComponent(g);
            Graphics2D g2 = (Graphics2D) g.create();
            g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
            g2.setRenderingHint(RenderingHints.KEY_TEXT_ANTIALIASING, RenderingHints.VALUE_TEXT_ANTIALIAS_ON);

            BigDecimal max = BigDecimal.ZERO;
            for (BigDecimal v : datos.values()) {
                if (v.compareTo(max) > 0) {
                    max = v;
                }
            }
            if (max.signum() == 0) {
                textoCentrado(g2, "Sin ventas en el periodo", getWidth(), getHeight());
                g2.dispose();
                return;
            }

            int n = datos.size();
            int arriba = 18, abajo = 24, margen = 4, hueco = 10;
            int altoMax = getHeight() - arriba - abajo;
            int anchoBarra = Math.max(4, (getWidth() - 2 * margen - hueco * (n - 1)) / n);
            int total = n * anchoBarra + (n - 1) * hueco;
            int x = (getWidth() - total) / 2;
            int base = getHeight() - abajo;

            g2.setFont(new Font(FUENTE, Font.PLAIN, 11));
            FontMetrics fm = g2.getFontMetrics();
            int cadaCuantos = Math.max(1, (int) Math.ceil(n / Math.max(1.0, getWidth() / 52.0)));
            int i = 0;
            for (Map.Entry<LocalDate, BigDecimal> e : datos.entrySet()) {
                int alto = e.getValue().multiply(BigDecimal.valueOf(altoMax))
                        .divide(max, 0, java.math.RoundingMode.HALF_UP).intValue();
                if (e.getValue().signum() > 0) {
                    alto = Math.max(alto, 3);
                }
                g2.setColor(BARRA);
                g2.fill(new RoundRectangle2D.Double(x, base - alto, anchoBarra, alto, 6, 6));

                g2.setColor(TEXTO_SUAVE);
                if (i % cadaCuantos == 0) {
                    String f = e.getKey().format(FECHA_CORTA);
                    g2.drawString(f, x + (anchoBarra - fm.stringWidth(f)) / 2, base + 16);
                }
                if (anchoBarra >= 46 && e.getValue().signum() > 0) {
                    String v = "$" + e.getValue().setScale(0, java.math.RoundingMode.HALF_UP);
                    g2.drawString(v, x + (anchoBarra - fm.stringWidth(v)) / 2, base - alto - 4);
                }
                x += anchoBarra + hueco;
                i++;
            }
            g2.dispose();
        }
    }

    private static class GraficaDona extends JPanel {
        private Map<String, BigDecimal> datos = new LinkedHashMap<>();

        GraficaDona() {
            setOpaque(false);
        }

        void setDatos(Map<String, BigDecimal> datos) {
            this.datos = datos;
            repaint();
        }

        private static Color colorDe(String categoria) {
            switch (categoria) {
                case "Productos": return new Color(143, 176, 126);
                case "Servicios": return new Color(127, 169, 181);
                case "Paquetes":  return new Color(219, 182, 124);
                default:          return new Color(170, 170, 170);
            }
        }

        @Override
        protected void paintComponent(Graphics g) {
            super.paintComponent(g);
            Graphics2D g2 = (Graphics2D) g.create();
            g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
            g2.setRenderingHint(RenderingHints.KEY_TEXT_ANTIALIASING, RenderingHints.VALUE_TEXT_ANTIALIAS_ON);

            BigDecimal suma = BigDecimal.ZERO;
            for (BigDecimal v : datos.values()) {
                suma = suma.add(v);
            }
            if (suma.signum() <= 0) {
                textoCentrado(g2, "Sin ventas en el periodo", getWidth(), getHeight());
                g2.dispose();
                return;
            }

            int d = Math.max(60, Math.min(getHeight() - 8, (int) (getWidth() * 0.55)));
            int x0 = 4;
            int y0 = (getHeight() - d) / 2;

            double inicio = 90;
            for (Map.Entry<String, BigDecimal> e : datos.entrySet()) {
                double extension = -360.0 * e.getValue().doubleValue() / suma.doubleValue();
                g2.setColor(colorDe(e.getKey()));
                g2.fill(new Arc2D.Double(x0, y0, d, d, inicio, extension, Arc2D.PIE));
                inicio += extension;
            }
            int hueco = (int) (d * 0.5);
            g2.setColor(Color.WHITE);
            g2.fill(new Ellipse2D.Double(x0 + (d - hueco) / 2.0, y0 + (d - hueco) / 2.0, hueco, hueco));

            g2.setFont(new Font(FUENTE, Font.PLAIN, 14));
            FontMetrics fm = g2.getFontMetrics();
            int lx = x0 + d + 24;
            int paso = 30;
            int ly = (getHeight() - paso * datos.size()) / 2 + paso / 2;
            for (Map.Entry<String, BigDecimal> e : datos.entrySet()) {
                int pct = (int) Math.round(e.getValue().doubleValue() * 100 / suma.doubleValue());
                g2.setColor(colorDe(e.getKey()));
                g2.fill(new Ellipse2D.Double(lx, ly - 6, 12, 12));
                g2.setColor(TEXTO_SUAVE);
                g2.drawString(e.getKey() + "  " + pct + "%", lx + 20, ly + fm.getAscent() / 2 - 1);
                ly += paso;
            }
            g2.dispose();
        }
    }

    private static void textoCentrado(Graphics2D g2, String texto, int ancho, int alto) {
        g2.setFont(new Font(FUENTE, Font.PLAIN, 14));
        g2.setColor(new Color(150, 160, 145));
        FontMetrics fm = g2.getFontMetrics();
        g2.drawString(texto, (ancho - fm.stringWidth(texto)) / 2, alto / 2);
    }
