    private void mostrarSugerencias() {
        if (modoPaquetes) {
            filtrarPaquetes();
            return;
        }
        String texto = txtBuscarProducto.getText().trim().toLowerCase();
        if (!txtBuscarProducto.isShowing()
                || texto.isEmpty() || esPlaceholder(texto)) {
            popupBusqueda.setVisible(false);
            return;
        }
        modeloSugerencias.clear();
        for (Producto p : catalogo) {
            if (p.getNombre().toLowerCase().contains(texto)) {
                modeloSugerencias.addElement(p);
                if (modeloSugerencias.size() >= 8) break;
            }
        }
        if (modeloSugerencias.isEmpty()) {
            popupBusqueda.setVisible(false);
            return;
        }
        popupBusqueda.setPopupSize(txtBuscarProducto.getWidth(),
                modeloSugerencias.size() * lstSugerencias.getFixedCellHeight() + 4);
        popupBusqueda.show(txtBuscarProducto, 0, txtBuscarProducto.getHeight());
        txtBuscarProducto.requestFocusInWindow();
    }

    private void elegirSugerencia(Producto p) {
        popupBusqueda.setVisible(false);
        if (p.getExistencias() == null || p.getExistencias() <= 0) {
            mostrarError("\"" + p.getNombre() + "\" esta agotado.");
            return;
        }
        agregarAlCarrito(p);
        txtBuscarProducto.setText("");
        txtBuscarProducto.requestFocusInWindow();
    }   

    private void cargarBotonesProductos() {
    if (modoPaquetes) {
        filtrarPaquetes();
        return;
    }
    visibles.clear();

    for (Producto p : catalogo) {
        if (visibles.size() >= botonesProducto.length) {
            break;
        }

        visibles.add(p);
    }

    mostrarProductos();
}


    private void mostrarProductos() {
        if (modoPaquetes) {
            mostrarPaquetes();
            return;
        }

        for (int i = 0; i < botonesProducto.length; i++) {
            JButton boton = botonesProducto[i];
            if (i < visibles.size()) {
                Producto p = visibles.get(i);
                boolean disponible = p.getExistencias() != null && p.getExistencias() > 0;
                double precioFinal = precioConDescuento(p);
                boton.setText("<html><center>" + escapar(p.getNombre()) + "<br>" + (disponible ? moneda.format(precioFinal): "Agotado") + "</center></html>");
                boton.setEnabled(disponible);
            } else {
                boton.setText("");
                boton.setEnabled(false);
            }
        }
    }
    
    private void agregarAlCarrito(Producto p) {
    int actual = carrito.getOrDefault(p.getIdProducto(), 0);
    int enPaquetes = reservadoPorPaquetes().getOrDefault(p.getIdProducto(), 0);

    if (actual + 1 + enPaquetes > p.getExistencias()) {
        mostrarError("No hay mas existencias de \""
                + p.getNombre()
                + "\" (disponibles: "
                + p.getExistencias() + ").");
        return;
    }

    carrito.put(p.getIdProducto(), actual + 1);
    refrescarCarrito();
}

    public void agregarServicioAlCarrito(DetalleVentaServicio detalle) {
        if (detalle == null || detalle.getServicio() == null ||
                detalle.getServicio().getIdServicio() == null ||
                detalle.getCantidad() == null || detalle.getCantidad() < 1 ||
                detalle.getNombreCliente() == null || detalle.getNombreCliente().isBlank()) {
            throw new IllegalArgumentException("Los datos del servicio no son validos.");
        }
        if (detalle.getProductoMaterial() == null || detalle.getProductoMaterial().getIdProducto() == null ||
                detalle.getDescripcionTrabajo() == null || detalle.getDescripcionTrabajo().isBlank()) {
            throw new IllegalArgumentException("Selecciona un material y escribe la descripcion del trabajo.");
        }
        int materialId = detalle.getProductoMaterial().getIdProducto();
        int reservado = carrito.getOrDefault(materialId, 0);
        for (DetalleVentaServicio otro : carritoServicios) {
            if (otro.getProductoMaterial() != null &&
                    materialId == otro.getProductoMaterial().getIdProducto()) {
                reservado += otro.getCantidad();
            }
        }
        if (detalle.getProductoMaterial().getExistencias() < reservado + detalle.getCantidad()) {
            throw new IllegalArgumentException("No hay suficientes materiales o existencias para agregar el servicio.");
        }
        carritoServicios.add(detalle);
        refrescarCarrito();
    }

