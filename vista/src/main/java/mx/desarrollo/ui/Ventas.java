    //  Abrir / Cerrar caja

    private static final java.time.format.DateTimeFormatter FECHA_HORA_CAJA =
            java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");
    private javax.swing.Timer relojCaja;

    private void iniciarRelojCaja() {
        actualizarTiempoCaja();
        relojCaja = new javax.swing.Timer(1000, e -> actualizarTiempoCaja());
        relojCaja.start();
        addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosed(java.awt.event.WindowEvent e) {
                relojCaja.stop();
            }
        });
    }

    private void actualizarTiempoCaja() {
        mx.desarrollo.delegate.SesionCaja.Apertura ap = mx.desarrollo.delegate.SesionCaja.de(usuarioActual);
        if (ap == null) {
            jLabel4.setText("Tiempo en caja: --:--:--");
            return;
        }
        long s = Math.max(0, java.time.Duration.between(ap.getHoraApertura(), java.time.LocalDateTime.now()).getSeconds());
        jLabel4.setText(String.format("Tiempo en caja: %d:%02d:%02d", s / 3600, (s % 3600) / 60, s % 60));
    }

    private void abrirCaja() {
        if (usuarioActual == null) {
            JOptionPane.showMessageDialog(this, "No hay un usuario en sesión.", "Abrir caja", JOptionPane.WARNING_MESSAGE);
            return;
        }
        mx.desarrollo.delegate.SesionCaja.Apertura actual = mx.desarrollo.delegate.SesionCaja.de(usuarioActual);
        if (actual != null) {
            JOptionPane.showMessageDialog(this,
                    "La caja ya está abierta.\n\n"
                    + "Abierta el: " + actual.getHoraApertura().format(FECHA_HORA_CAJA) + "\n"
                    + "Fondo inicial: " + moneda.format(actual.getFondoInicial()),
                    "Abrir caja", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        AbrirCajaDialog dialogo = new AbrirCajaDialog(this, usuarioActual);
        dialogo.setVisible(true);
        mx.desarrollo.delegate.SesionCaja.Apertura nueva = dialogo.getApertura();
        if (nueva != null) {
            actualizarTiempoCaja();
            JOptionPane.showMessageDialog(this,
                    "Caja abierta con un fondo inicial de " + moneda.format(nueva.getFondoInicial()) + ".",
                    "Abrir caja", JOptionPane.INFORMATION_MESSAGE);
        }
    }

    private void cerrarCaja() {
        if (usuarioActual == null) {
            JOptionPane.showMessageDialog(this, "No hay un usuario en sesión.", "Cerrar caja", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!carrito.isEmpty() || !carritoServicios.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Hay una venta en proceso.\nCóbrala o límpiala antes de cerrar la caja.",
                    "Cerrar caja", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            mx.desarrollo.delegate.ResumenCorte turno = ServiceFacadeLocator.getInstanceFacadeCorteCaja()
                    .consultarTurno(usuarioActual, usuarioActual);
            mx.desarrollo.delegate.SesionCaja.Apertura ap = mx.desarrollo.delegate.SesionCaja.de(usuarioActual);

            if (turno.getVentas().isEmpty()) {
                if (ap == null) {
                    JOptionPane.showMessageDialog(this,
                            "No hay ventas pendientes de corte ni una caja abierta.",
                            "Cerrar caja", JOptionPane.INFORMATION_MESSAGE);
                    return;
                }
                int op = JOptionPane.showConfirmDialog(this,
                        "No hay ventas en este turno.\n¿Cerrar la caja sin generar corte?",
                        "Cerrar caja", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
                if (op == JOptionPane.YES_OPTION) {
                    mx.desarrollo.delegate.SesionCaja.cerrar(usuarioActual.getIdUsuario());
                    actualizarTiempoCaja();
                    JOptionPane.showMessageDialog(this, "Caja cerrada.", "Cerrar caja", JOptionPane.INFORMATION_MESSAGE);
                }
                return;
            }

            CerrarCajaDialog dialogo = new CerrarCajaDialog(this, usuarioActual, turno);
            dialogo.setVisible(true);
            if (dialogo.getCorteCerrado() != null) {
                actualizarTiempoCaja();
            }
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Cerrar caja", JOptionPane.WARNING_MESSAGE);
        } catch (RuntimeException | ExceptionInInitializerError ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this,
                    "No se pudo completar la operación con la base de datos.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

