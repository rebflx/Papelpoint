    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {
        Usuario u = new Usuario();
        u.setNombrePersona(txtNombre.getText());
        u.setNombreUsuario(txtUsuario.getText());
        u.setRol(rolSeleccionadoBD());
        u.setActivo(true);

        try {
            facade().guardar(u, new String(txtContrasena.getPassword()));
        } catch (IllegalArgumentException ex) {
            aviso(ex.getMessage());
            return;
        } catch (Throwable ex) {
            errorBD(ex);
            return;
        }
        limpiarFormulario();
        cargarUsuarios();
        JOptionPane.showMessageDialog(this, "Usuario guardado correctamente.",
                "Listo", JOptionPane.INFORMATION_MESSAGE);
    }

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {
        if (seleccionado == null) {
            aviso("Selecciona un usuario de la tabla para modificarlo.");
            return;
        }
        Usuario u = copiar(seleccionado);
        u.setNombrePersona(txtNombre.getText());
        u.setNombreUsuario(txtUsuario.getText());
        u.setRol(rolSeleccionadoBD());

        try {
            facade().modificar(u, new String(txtContrasena.getPassword()));
        } catch (IllegalArgumentException ex) {
            aviso(ex.getMessage());
            return;
        } catch (Throwable ex) {
            errorBD(ex);
            return;
        }
        limpiarFormulario();
        cargarUsuarios();
        JOptionPane.showMessageDialog(this, "Usuario modificado correctamente.",
                "Listo", JOptionPane.INFORMATION_MESSAGE);
    }

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {
        if (seleccionado == null) {
            aviso("Selecciona un usuario de la tabla para eliminarlo.");
            return;
        }
        if ("ADMIN".equals(seleccionado.getRol()) && contarAdminsActivos() <= 1) {
            aviso("No se puede eliminar al único administrador.");
            return;
        }
        int r = JOptionPane.showConfirmDialog(this,
                "¿Eliminar al usuario \"" + seleccionado.getNombreUsuario() + "\"?\n"
                + "Ya no podrá iniciar sesión.",
                "Confirmar", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (r != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            facade().desactivar(copiar(seleccionado));
        } catch (Throwable ex) {
            errorBD(ex);
            return;
        }
        limpiarFormulario();
        cargarUsuarios();
    }

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {
        limpiarFormulario();
    }


    // Tabla / datos


    private void cargarUsuarios() {
        try {
            List<Usuario> lista = facade().listar();
            todos = new ArrayList<>();
            for (Usuario u : lista) {
                if (Boolean.TRUE.equals(u.getActivo())) {
                    todos.add(u);
                }
            }
        } catch (Throwable ex) {
            errorBD(ex);
            todos = new ArrayList<>();
        }
        aplicarFiltro();
    }

    private void aplicarFiltro() {
        String q = txtBuscar.getText() == null ? "" : txtBuscar.getText().trim().toLowerCase();
        DefaultTableModel modelo = (DefaultTableModel) tablaUsuarios.getModel();

        modelo.setRowCount(0);
        visibles.clear();
        for (Usuario u : todos) {
            boolean coincide = q.isEmpty()
                    || u.getNombrePersona().toLowerCase().contains(q)
                    || u.getNombreUsuario().toLowerCase().contains(q);
            if (coincide) {
                visibles.add(u);
                modelo.addRow(new Object[]{
                    String.format("%03d", u.getIdUsuario()),
                    u.getNombrePersona(),
                    u.getNombreUsuario(),
                    "••••••",
                    rolParaVista(u.getRol())
                });
            }
        }
        seleccionado = null;
    }

    private void usuarioSeleccionadoEnTabla() {
        int fila = tablaUsuarios.getSelectedRow();
        if (fila < 0 || fila >= visibles.size()) {
            seleccionado = null;
            return;
        }
        seleccionado = visibles.get(fila);
        txtNombre.setText(seleccionado.getNombrePersona());
        txtUsuario.setText(seleccionado.getNombreUsuario());
        txtContrasena.setText("");
        cmbRol.setSelectedItem(rolParaVista(seleccionado.getRol()));
    }

    private void limpiarFormulario() {
        txtNombre.setText("");
        txtUsuario.setText("");
        txtContrasena.setText("");
        cmbRol.setSelectedIndex(0);
        tablaUsuarios.clearSelection();
        seleccionado = null;
    }


    // Auxiliares


    private FacadeUsuario facade() {
        return ServiceFacadeLocator.getInstanceFacadeUsuario();
    }

    private String rolSeleccionadoBD() {
        return ROLES_BD[cmbRol.getSelectedIndex()];
    }

    private String rolParaVista(String rolBD) {
        for (int i = 0; i < ROLES_BD.length; i++) {
            if (ROLES_BD[i].equals(rolBD)) {
                return ROLES_VISTA[i];
            }
        }
        return rolBD;
    }

    private int contarAdminsActivos() {
        int n = 0;
        for (Usuario u : todos) {
            if ("ADMIN".equals(u.getRol())) {
                n++;
            }
        }
        return n;
    }

    private Usuario copiar(Usuario o) {
        Usuario c = new Usuario();
        c.setIdUsuario(o.getIdUsuario());
        c.setNombrePersona(o.getNombrePersona());
        c.setNombreUsuario(o.getNombreUsuario());
        c.setContrasena(o.getContrasena());
        c.setActivo(o.getActivo());
        c.setRol(o.getRol());
        return c;
    }

    private void aviso(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Revisa los datos", JOptionPane.WARNING_MESSAGE);
    }

