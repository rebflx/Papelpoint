    public CancelarVentaDialog(java.awt.Frame parent, Usuario usuario) {
        this(parent, true);
        this.usuario = usuario;

        cmbVentas.setRenderer(new DefaultListCellRenderer() {
            @Override
            public Component getListCellRendererComponent(JList<?> l, Object v, int i,
                                                          boolean sel, boolean foc) {
                super.getListCellRendererComponent(l, v, i, sel, foc);
                if (v instanceof Venta) {
                    Venta venta = (Venta) v;
                    setText(DelegateVenta.folio(venta.getIdVenta()) + "  -  "
                            + venta.getFecha().format(FECHA));
                }
                return this;
            }
        });

        cmbVentas.addActionListener(e -> mostrarTicket());
        btnCerrar.addActionListener(e -> dispose());
        btnCancelarVenta.addActionListener(e -> cancelar());

        pack();
        setLocationRelativeTo(parent);
        cargarVentas();
    }

    public boolean huboCancelacion() {
        return huboCancelacion;
    }

    private void cargarVentas() {
        try {
            List<Venta> ventas = ServiceFacadeLocator.getInstanceFacadeVenta()
                    .ventasCancelablesDelTurno(usuario);
            cmbVentas.setModel(new DefaultComboBoxModel<>(ventas.toArray(new Venta[0])));
        } catch (Exception | ExceptionInInitializerError ex) {
            cmbVentas.setModel(new DefaultComboBoxModel<>());
            JOptionPane.showMessageDialog(this, "No se pudieron cargar las ventas: " + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
        boolean hay = cmbVentas.getItemCount() > 0;
        cmbVentas.setEnabled(hay);
        btnCancelarVenta.setEnabled(hay);
        if (hay) {
            cmbVentas.setSelectedIndex(0);
            mostrarTicket();
        } else {
            txtTicket.setText("\n  No hay ventas en este turno\n  que se puedan cancelar.");
        }
    }

     private static double num(Number n) {
        return n == null ? 0 : n.doubleValue();
    }
     
      private void mostrarTicket() {
        Venta v = (Venta) cmbVentas.getSelectedItem();
        if (v == null) {
            return;
        }
        try {
            var facade = ServiceFacadeLocator.getInstanceFacadeVenta();
            List<DetalleVentaProducto> prods = facade.detallesDeVenta(v.getIdVenta());
            List<DetalleVentaServicio> servs = facade.detallesServicioDeVenta(v.getIdVenta());
            List<DetalleVentaPaquete> paqs = facade.detallesPaqueteDeVenta(v.getIdVenta());
 
            String igual = "=".repeat(ANCHO);
            String guion = "-".repeat(ANCHO);
            StringBuilder sb = new StringBuilder();
            sb.append(centrar("Papelerias Las Californias")).append('\n');
            sb.append(igual).append('\n');
            sb.append("Fecha: ").append(v.getFecha().format(FECHA)).append('\n');
            sb.append("Folio: ").append(DelegateVenta.folio(v.getIdVenta())).append('\n');
            sb.append("Cajero: ").append(v.getUsuario().getNombrePersona()).append('\n');
            sb.append("Pago: ").append(v.getMetodoPago()).append('\n');
            sb.append(igual).append('\n');
            sb.append(String.format("%-18s %4s %9s%n", "PRODUCTO", "CANT", "IMPORTE"));
            for (DetalleVentaProducto d : prods) {
                sb.append(linea(d.getProducto().getNombre(), d.getCantidad(),
                        d.getPrecioUnitario() * d.getCantidad()));
            }
            for (DetalleVentaServicio d : servs) {
                int cantidad = (int) num(d.getCantidad());
                sb.append(linea(d.getServicio().getNombre(), cantidad,
                        num(d.getPrecioUnitario()) * cantidad));
            }
            for (DetalleVentaPaquete d : paqs) {
                int cantidad = (int) num(d.getCantidad());
                sb.append(linea(d.getPaquete().getNombrePaquete(), cantidad,
                        num(d.getPrecioUnitario()) * cantidad));
            }
            sb.append(guion).append('\n');
            sb.append(String.format("%-14s %19s%n", "TOTAL:", moneda.format(v.getTotal())));
            sb.append(igual).append('\n');
            sb.append(centrar("¡GRACIAS POR SU COMPRA!")).append('\n');
            txtTicket.setText(sb.toString());
            txtTicket.setCaretPosition(0);
        } catch (Exception | ExceptionInInitializerError ex) {
            txtTicket.setText("No se pudo cargar el ticket: " + ex.getMessage());
        }
    }

    private String linea(String nombre, int cant, double importe) {
        String n = nombre == null ? "" : nombre;
        if (n.length() > 18) {
            n = n.substring(0, 17) + ".";
        }
        return String.format("%-18s %4d %9s%n", n, cant, moneda.format(importe));
    }

    private static String centrar(String t) {
        int pad = Math.max(0, (ANCHO - t.length()) / 2);
        return " ".repeat(pad) + t;
    }

    private void cancelar() {
        Venta v = (Venta) cmbVentas.getSelectedItem();
        if (v == null) {
            return;
        }
        int op = JOptionPane.showConfirmDialog(this,
                "¿Cancelar la venta " + DelegateVenta.folio(v.getIdVenta()) + " por "
                        + moneda.format(v.getTotal()) + "?\n"
                        + "Se regresarán las existencias al inventario y se quitará del historial.",
                "Cancelar venta", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (op != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            ServiceFacadeLocator.getInstanceFacadeVenta().cancelarVenta(usuario, v.getIdVenta());
            huboCancelacion = true;
            JOptionPane.showMessageDialog(this, "Venta cancelada.", "Cancelar venta",
                    JOptionPane.INFORMATION_MESSAGE);
            cargarVentas();
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Cancelar venta",
                    JOptionPane.WARNING_MESSAGE);
            cargarVentas();
        } catch (Exception | ExceptionInInitializerError ex) {
            JOptionPane.showMessageDialog(this, "No se pudo cancelar la venta: " + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
