 public void configurar(String titulo, String detalle,
        java.awt.Color fondo, Runnable alClic) {

    lblTitulo.setText(titulo);
    lblDetalle.setText(detalle);

    lblTitulo.setFont(new java.awt.Font("Segoe UI", 1, 13));
    lblDetalle.setFont(new java.awt.Font("Segoe UI", 0, 12));

    lblTitulo.setForeground(new java.awt.Color(35, 35, 35));
    lblDetalle.setForeground(new java.awt.Color(100, 100, 100));

    java.awt.Color colorBase = new java.awt.Color(248, 249, 250);
    java.awt.Color colorHover = new java.awt.Color(235, 240, 244);

    setBackground(colorBase);

    setBorder(javax.swing.BorderFactory.createMatteBorder(
            0, 4, 1, 0, fondo
    ));

    for (java.awt.event.MouseListener ml : getMouseListeners()) {
        removeMouseListener(ml);
    }

    setCursor(alClic == null
            ? java.awt.Cursor.getDefaultCursor()
            : java.awt.Cursor.getPredefinedCursor(
                    java.awt.Cursor.HAND_CURSOR));

    if (alClic != null) {
        java.awt.event.MouseAdapter mouse =
                new java.awt.event.MouseAdapter() {

            @Override
            public void mouseEntered(java.awt.event.MouseEvent e) {
                setBackground(colorHover);
            }

            @Override
            public void mouseExited(java.awt.event.MouseEvent e) {
                setBackground(colorBase);
            }

            @Override
            public void mouseClicked(java.awt.event.MouseEvent e) {
                alClic.run();
            }
        };

        addMouseListener(mouse);
        lblTitulo.addMouseListener(mouse);
        lblDetalle.addMouseListener(mouse);
    }
}
